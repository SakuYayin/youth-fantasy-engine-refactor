/** 素材分类 id（与上游 materialData.ts 的分类结构一一对应）。 */
export type MaterialCategoryId =
  | 'character'
  | 'story-structure'
  | 'world-framework'
  | 'emotion'
  | 'writing'

/** 分类定义。 */
export interface MaterialCategoryDef {
  readonly id: MaterialCategoryId
  readonly name: string
}

/** 素材条目（上游 block → 扁平化：标题 / 摘要 / 正文）。 */
export interface MaterialItem {
  readonly id: string
  readonly category: MaterialCategoryId
  /** 标题（列表与展开详情共用）。 */
  readonly title: string
  /** 一句话摘要（列表默认展示）。 */
  readonly summary: string
  /** 正文（展开后展示；纯文本，换行分段）。 */
  readonly content: string
}

/** 筛选条件（纯函数入参；category 为 'all' 表示全部）。 */
export interface MaterialFilter {
  readonly category: MaterialCategoryId | 'all'
  readonly keyword: string
}

