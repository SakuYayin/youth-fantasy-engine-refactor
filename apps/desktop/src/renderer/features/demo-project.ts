/**
 * 把 `maxChapters` 归一化到 `[0, ALL_CHAPTER_COUNT]`。
 *
 * 未传、`NaN`、`Infinity` 一律回落到 `ALL_CHAPTER_COUNT`（缺省给**全部可用章节**）；
 * 小数向下取整，负数归零。
 */
function normalizeMaxChapters(raw: number | undefined): number {
  if (raw === undefined || !Number.isFinite(raw)) return ALL_CHAPTER_COUNT
  return Math.min(ALL_CHAPTER_COUNT, Math.max(0, Math.floor(raw)))
}

/**
 * 字数文案：`>= 10000` 时按「万」保留一位小数（如 `约 9.0 万字`），否则按「字」（如 `约 880 字`）。
 *
 * 口径对齐 `snapshot.charCount` 的「字」—— 直接累加 `body.length`，不做字素簇 / 标点剔除。
 */
function formatCharCount(charCount: number): string {
  if (charCount >= 10000) return `约 ${(charCount / 10000).toFixed(1)} 万字`
  return `约 ${charCount} 字`
}

/**
 * 组装示范项目种子。
 *
 * @param options.maxChapters 章数上限，按卷序从头截取：受影响的卷只保留前面的章，
 *   被截空的卷不会出现在结果里（但**卷内顺序与卷间顺序永远不变**）。
 *   缺省 = `21`（上游 `CH1`…`CH21` 全部可用章节）。这个开关存在的意义是控制包体 ——
 *   正文是种子里最重的部分。
 * @returns 深度冻结的 `DemoProjectSeed`。每次调用返回**新**对象（切片产物），可安全长期持有。
 *
 * @example
 * ```ts
 * buildDemoProjectSeed().volumes.length                          // 2（契约两卷）
 * buildDemoProjectSeed().volumes[1]?.chapters.length             // 11（第 11–21 章）
 * buildDemoProjectSeed({ maxChapters: 3 }).volumes[0]?.chapters.length // 3，且只剩第一卷
 * ```
 */
export function buildDemoProjectSeed(options?: { readonly maxChapters?: number }): DemoProjectSeed {
  let remaining = normalizeMaxChapters(options?.maxChapters)
  const volumes: DemoVolumeSeed[] = []
  for (const volume of RAW_VOLUMES) {
    if (remaining <= 0) break
    const chapters = volume.chapters.slice(0, remaining)
    if (chapters.length === 0) continue
    remaining -= chapters.length
    volumes.push(Object.freeze({ title: volume.title, chapters: Object.freeze(chapters) }))
  }
  return Object.freeze({
    name: DEMO_PROJECT_NAME,
    summary: DEMO_PROJECT_SUMMARY,
    volumes: Object.freeze(volumes),
  })
}

/**
 * 缺省种子的规模统计（**与 `buildDemoProjectSeed()` 无参调用严格一致**）。
 *
 * 供欢迎向导 / 作品中心在按钮旁显示「两卷二十一章 · 约 1.7 万字」这类信息，无需自己遍历。
 * ⚠️ 具体字数随摘录长度变化，**不要**在别处硬编码，一律以本函数返回值为准。
 * `charCount` 就是所有 `body.length` 之和（与 `snapshot.charCount` 同口径）；
 * `charCountText` 是它的展示形式（`>= 10000` 时按「万」保留一位小数）。
 */
export function demoProjectStats(): {
  readonly volumeCount: number
  readonly chapterCount: number
  readonly charCount: number
  readonly charCountText: string
} {
  const seed = buildDemoProjectSeed()
  let chapterCount = 0
  let charCount = 0
  for (const volume of seed.volumes) {
    for (const chapter of volume.chapters) {
      chapterCount += 1
      charCount += chapter.body.length
    }
  }
  return Object.freeze({
    volumeCount: seed.volumes.length,
    chapterCount,
    charCount,
    charCountText: formatCharCount(charCount),
  })
}
